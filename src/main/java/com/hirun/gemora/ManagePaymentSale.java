    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String amountReceivedText = jTextField3.getText().trim();
        String paymentMethod = (String) jComboBox1.getSelectedItem();
        String buyerName = (String) jComboBox2.getSelectedItem();
        String description = jTextField2.getText().trim(); // Get description text

        DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();

        if (amountReceivedText.isEmpty() || paymentMethod.isEmpty() || buyerName.isEmpty() || description.isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields must be filled, including Description!", "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            JSONObject buyer = BuyerDAO.readBuyerByName(buyerName);
            int buyerId = buyer.getInt("buyer_id");
            double amountReceived = Double.parseDouble(amountReceivedText);

            String insertQuery = "INSERT INTO PaymentFromBuyer (sale_id, buyer_id, amount_received, payment_method, payment_date, description) VALUES (?, ?, ?, ?, NOW(), ?)";

            try (Connection conn = DatabaseConnection.getConnection(); PreparedStatement pstmt = conn.prepareStatement(insertQuery, Statement.RETURN_GENERATED_KEYS)) {
                pstmt.setInt(1, materialId);  // Use materialId as sale_id
                pstmt.setInt(2, buyerId);
                pstmt.setDouble(3, amountReceived);
                pstmt.setString(4, paymentMethod);
                pstmt.setString(5, description);  // Set the description field

                int affectedRows = pstmt.executeUpdate();

                if (affectedRows > 0) {
                    ResultSet generatedKeys = pstmt.getGeneratedKeys();
                    if (generatedKeys.next()) {
                        int newPaymentId = generatedKeys.getInt(1);
                        Timestamp paymentDate = new Timestamp(System.currentTimeMillis());

                        // Add new payment details to the table
                        tableModel.addRow(new Object[]{newPaymentId, amountReceived, paymentDate, paymentMethod, description});
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Error: Payment not added!", "Failure", JOptionPane.ERROR_MESSAGE);
                }

            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values for Amount!", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed


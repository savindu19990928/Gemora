    public ManagePaymentSale(int materialId) {
        this.materialId = materialId;
        initComponents();
        String query = "SELECT buyer_payment_id, amount_received, payment_date, payment_method, description FROM PaymentFromBuyer WHERE sale_id = ?";

        try (Connection conn = DatabaseConnection.getConnection(); PreparedStatement stmt = conn.prepareStatement(query)) {
            stmt.setInt(1, materialId); // Using materialId as sale_id

            try (ResultSet rs = stmt.executeQuery()) {
                DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();
                tableModel.setRowCount(0);
                while (rs.next()) {
                    int paymentId = rs.getInt("buyer_payment_id");
                    double amountReceived = rs.getDouble("amount_received");
                    Timestamp paymentDate = rs.getTimestamp("payment_date");
                    String paymentMethod = rs.getString("payment_method");
                    String description = rs.getString("description");

                    // Add row to table with description
                    tableModel.addRow(new Object[]{paymentId, amountReceived, paymentDate, paymentMethod, description});
                }
            }
            List<JSONObject> buyers = BuyerDAO.readBuyers(); // Fetching buyer data
            List<String> buyerNames = buyers.stream()
                    .map(json -> json.getString("name"))
                    .collect(Collectors.toList());
            cModel = new DefaultComboBoxModel<>(buyerNames.toArray(String[]::new));
            jComboBox2.setModel(cModel); // Setting the ComboBox model with buyer names
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading payments: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }


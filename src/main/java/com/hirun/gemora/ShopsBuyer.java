    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        String name = jTextField1.getText().trim();  // Get the buyer name from the text field
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter a valid buyer name.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Show a confirmation dialog before deleting
        int confirm = JOptionPane.showConfirmDialog(null, "Are you sure you want to delete this buyer?",
                "Confirm Deletion", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return; // Stop deletion if the user selects "No"
        }

        try {
            BuyerDAO.removeBuyer(name);

            // Clear the input field after deletion
            jTextField1.setText("");

            // Show success message
            JOptionPane.showMessageDialog(null, "Buyer removed successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

        } catch (Exception e) {
            // Show an error message if an exception occurs
            JOptionPane.showMessageDialog(null, "An error occurred: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();  // Optionally log the stack trace for debugging
        }
    }//GEN-LAST:event_jButton4ActionPerformed



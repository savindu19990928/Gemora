    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String name = jTextField1.getText().trim();  // Get the buyer name from the text field
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter a valid buyer name.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            // Fetch the buyer information by name from the database
            JSONObject buyer = BuyerDAO.readBuyerByName(name);

            // Check if the buyer exists in the database
            if (buyer == null) {
                JOptionPane.showMessageDialog(null, "Buyer not found.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Populate the text fields with the buyer's details
            jTextField2.setText(buyer.getString("address"));
            jTextField3.setText(buyer.getString("ownerName"));
            jTextField4.setText(buyer.getString("contact_info"));

        } catch (Exception e) {
            // Handle any exceptions (e.g., network issues, database errors)
            JOptionPane.showMessageDialog(null, "An error occurred while fetching the buyer details: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();  // Optionally log the stack trace for debugging
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            // Get input values from text fields
            String name = jTextField1.getText().trim();
            String address = jTextField2.getText().trim();
            String ownerName = jTextField3.getText().trim();
            String contactInfo = jTextField4.getText().trim();

            // Validate input fields
            if (name.isEmpty() || address.isEmpty() || ownerName.isEmpty() || contactInfo.isEmpty()) {
                JOptionPane.showMessageDialog(null, "All fields are required!", "Input Error", JOptionPane.ERROR_MESSAGE);
                return; // Stop execution if validation fails
            }

            // Attempt to add buyer
            BuyerDAO.addBuyer(name, address, ownerName, contactInfo);

            // Clear the fields after adding
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");

            // Show a success message
            JOptionPane.showMessageDialog(null, "Buyer added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

        } catch (Exception e) {
            // Show an error message if an exception occurs
            JOptionPane.showMessageDialog(null, "An error occurred: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace(); // Log error details for debugging
        }
    }//GEN-LAST:event_jButton2ActionPerformed


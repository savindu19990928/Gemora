    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // Assuming you have JTextFields for input in your form
        String title = jTextField1.getText().trim();
        String description = jTextField2.getText().trim();
        String amountText = jTextField3.getText().trim();

        DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();

        // Check if fields are empty before proceeding
        if (title.isEmpty() || description.isEmpty() || amountText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields must be filled!", "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double amount = Double.parseDouble(amountText);

            String insertQuery = "INSERT INTO MaterialAdditionalCost (material_id, title, cost_description, cost_amount) VALUES (?, ?, ?, ?)";

            try (Connection conn = DatabaseConnection.getConnection(); PreparedStatement pstmt = conn.prepareStatement(insertQuery, Statement.RETURN_GENERATED_KEYS)) {
                pstmt.setInt(1, materialId);
                pstmt.setString(2, title);
                pstmt.setString(3, description);
                pstmt.setDouble(4, amount);
                int affectedRows = pstmt.executeUpdate();

                if (affectedRows > 0) {
                    ResultSet generatedKeys = pstmt.getGeneratedKeys();
                    if (generatedKeys.next()) {
                        int newCostId = generatedKeys.getInt(1);
                        tableModel.addRow(new Object[]{newCostId, materialId, description, amount});
                    }
                    JOptionPane.showMessageDialog(this, "Row added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "Error: Row not added!", "Failure", JOptionPane.ERROR_MESSAGE);
                }

            } catch (SQLException e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numbers for Material ID and Amount!", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

